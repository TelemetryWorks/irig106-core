use irig106_core::{Event, Inspection, InspectionLimits, PacketReader, ReaderLimits};
use std::{
    alloc::{GlobalAlloc, Layout, System},
    fs::File,
    hint::black_box,
    io::{BufWriter, Read, Write},
    sync::atomic::{AtomicBool, AtomicU64, Ordering::Relaxed},
    time::Instant,
};
#[allow(dead_code)]
struct Counter;
static COUNT: AtomicBool = AtomicBool::new(false);
static ALLOCS: AtomicU64 = AtomicU64::new(0);
static REALLOCS: AtomicU64 = AtomicU64::new(0);
static BYTES: AtomicU64 = AtomicU64::new(0);
// Unsafe is confined to this external measuring harness, never the core crate.
unsafe impl GlobalAlloc for Counter {
    unsafe fn alloc(&self, l: Layout) -> *mut u8 {
        if COUNT.load(Relaxed) {
            ALLOCS.fetch_add(1, Relaxed);
            BYTES.fetch_add(l.size() as u64, Relaxed);
        }
        unsafe { System.alloc(l) }
    }
    unsafe fn dealloc(&self, p: *mut u8, l: Layout) {
        unsafe { System.dealloc(p, l) }
    }
    unsafe fn realloc(&self, p: *mut u8, l: Layout, n: usize) -> *mut u8 {
        if COUNT.load(Relaxed) {
            REALLOCS.fetch_add(1, Relaxed);
            BYTES.fetch_add(n as u64, Relaxed);
        }
        unsafe { System.realloc(p, l, n) }
    }
}
#[cfg(feature = "count-alloc")]
#[global_allocator]
static A: Counter = Counter;
fn frame(channel: u16, kind: u8, n: usize, seq: u8, rtc: u64) -> Vec<u8> {
    let mut p = vec![0u8; n];
    p[..2].copy_from_slice(&[0x25, 0xeb]);
    p[2..4].copy_from_slice(&channel.to_le_bytes());
    p[4..8].copy_from_slice(&(n as u32).to_le_bytes());
    p[8..12].copy_from_slice(&((n - 24) as u32).to_le_bytes());
    p[12] = if kind == 1 { 9 } else { 6 };
    p[13] = seq;
    p[15] = kind;
    p[16..22].copy_from_slice(&rtc.to_le_bytes()[..6]);
    let sum = (0..22).step_by(2).fold(0u16, |sum, i| {
        sum.wrapping_add(u16::from_le_bytes([p[i], p[i + 1]]))
    });
    p[22..24].copy_from_slice(&sum.to_le_bytes());
    for (i, b) in p[24..].iter_mut().enumerate() {
        *b = ((i * 37 + channel as usize * 13 + kind as usize) & 255) as u8;
    }
    p
}
fn generate(path: &str) {
    let mut out = BufWriter::with_capacity(1024 * 1024, File::create(path).unwrap());
    let mut seq = [0u8; 65];
    out.write_all(&frame(0, 1, 1024 * 1024, 0, 0)).unwrap();
    let kinds = [0x09, 0x19, 0x21, 0x29, 0x68, 0x11, 0x09, 0x21];
    for i in 0..2_000_000usize {
        let ch = (i % 64 + 1) as u16;
        let n = if i % 16384 == 16383 {
            524288
        } else if i % 4096 == 4095 {
            65536
        } else {
            [64, 128, 256, 512][i % 4]
        };
        out.write_all(&frame(
            ch,
            kinds[(ch as usize - 1) % 8],
            n,
            seq[ch as usize],
            i as u64 * 100,
        ))
        .unwrap();
        seq[ch as usize] = seq[ch as usize].wrapping_add(1);
    }
    out.flush().unwrap();
    println!(
        "generated bytes={} packets=2000001",
        std::fs::metadata(path).unwrap().len()
    );
}
fn scan(path: &str, mode: &str, instrument: bool) -> (u64, u64, u64, u64, u64, u64, f64) {
    let f = File::open(path).unwrap();
    let mut digest = 0u64;
    let mut count = 0u64;
    ALLOCS.store(0, Relaxed);
    REALLOCS.store(0, Relaxed);
    BYTES.store(0, Relaxed);
    COUNT.store(instrument, Relaxed);
    let start = Instant::now();
    if mode == "raw" {
        let mut f = f;
        let mut b = [0u8; 8192];
        loop {
            let n = f.read(&mut b).unwrap();
            if n == 0 {
                break;
            }
            digest = digest.wrapping_add(black_box(b[n - 1]) as u64);
        }
    } else {
        let mut reader =
            PacketReader::new(f, ReaderLimits::new().with_capture_bytes(134217728)).unwrap();
        let mut summary = Inspection::new(InspectionLimits::new(65, 256));
        while let Some(e) = reader
            .next_packet(|h| match mode {
                "prefix" => 4,
                "full" | "heavy" => h.data_length() as usize,
                _ => 0,
            })
            .unwrap()
        {
            if let Event::Packet(p) = &e {
                count += 1;
                digest = digest.wrapping_add(p.offset ^ p.header.data_length() as u64);
                if mode == "heavy" {
                    // Serial, dependent payload hash as a controlled CPU-work proxy, not an IRIG decoder.
                    for &b in &p.body_prefix {
                        digest = digest.rotate_left(5).wrapping_mul(0x100000001b3) ^ b as u64;
                    }
                } else if !p.body_prefix.is_empty() {
                    digest ^= black_box(p.body_prefix[0]) as u64;
                }
            }
            if mode == "summary" {
                summary.observe(&e).unwrap();
            }
        }
        if mode == "summary" {
            summary.finish();
            assert_eq!(summary.totals().packets, 2_000_001);
        }
        assert_eq!(count, 2_000_001);
    }
    let elapsed = start.elapsed().as_secs_f64();
    COUNT.store(false, Relaxed);
    black_box(digest);
    (
        count,
        ALLOCS.load(Relaxed),
        REALLOCS.load(Relaxed),
        BYTES.load(Relaxed),
        digest,
        std::fs::metadata(path).unwrap().len(),
        elapsed,
    )
}
fn main() {
    let args: Vec<_> = std::env::args().collect();
    if args.len() != 3 || !matches!(args[1].as_str(), "generate" | "bench") {
        eprintln!("usage: core-02-readonly-baseline <generate|bench> <fixture>");
        std::process::exit(2);
    }
    if args[1] == "generate" {
        generate(&args[2]);
        return;
    }
    let path = &args[2];
    println!(
        "mode,instrumented,rep,seconds,packets,bytes,packets_per_s,MB_per_s,allocs,reallocs,allocated_bytes,digest"
    );
    // A warm raw pass, excluded from all measurements; no cache flushing.
    black_box(scan(path, "raw", false));
    for mode in ["raw", "scan", "prefix", "full", "summary", "heavy"] {
        for rep in 0..4 {
            let instrument = rep == 3;
            let (n, a, r, b, d, size, t) = scan(path, mode, instrument);
            println!(
                "{mode},{instrument},{rep},{t:.9},{n},{size},{:.3},{:.3},{a},{r},{b},{d}",
                n as f64 / t,
                size as f64 / t / 1e6
            );
        }
    }
}
